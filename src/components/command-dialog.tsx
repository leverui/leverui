import { splitProps } from '../primitives/utils/split-props';
import { createMemo, type Accessor, type Component } from 'solid-js';
import { createOptionalContext, useOptionalContext } from '../primitives/utils/optional-context';
import { mergeProps } from '../primitives/utils/merge-props';
import { type JSX } from '@solidjs/web';
import { useDialogContext } from '../primitives/components/dialog';
import type { NativeHtmlAliases } from '../styled-system/native-html-aliases';
import { composeRecipeClassNames } from '../styled-system/recipe-class';
import type { PrimitiveNativeElementProps } from './primitive-native-element-props';
import { Dialog } from './dialog-exports';
import type { DialogContentProps } from './dialog-parts';
import type { DialogRootProps } from './dialog-props';
import { useCommandSource } from './command-context';
import type { CommandItem } from './command-types';

const CommandCloseContext = createOptionalContext<() => void>();
const CommandDialogTitleIdContext = createOptionalContext<Accessor<string | undefined>>();
/** Bind the polymorphic Dialog content renderer to its default native surface. */
const CommandDialogSurface = Dialog.Content as Component<DialogContentProps>;

/** Read the enclosing Command dialog's close action when present. */
export function useCommandDialogClose(): (() => void) | undefined {
  return useOptionalContext(CommandCloseContext);
}

/** Read the mounted dialog title's ID for a nested Command input. */
export function useCommandDialogTitleId(): Accessor<string | undefined> | undefined {
  return useOptionalContext(CommandDialogTitleIdContext);
}

/** Open a top-placed dialog and reset its Command source after exit. */
export function CommandDialog(props: DialogRootProps): JSX.Element {
  /** Read the nearest Command source while actions remain in this dialog. */
  const source = useCommandSource<CommandItem>();
  const [local, root] = splitProps(props, ['children', 'onEscapeKeyDown', 'onExitComplete']);

  /** Let nested Command pages consume Escape before the dialog closes. */
  function handleEscape(
    event: Parameters<NonNullable<DialogRootProps['onEscapeKeyDown']>>[0],
  ): void {
    local.onEscapeKeyDown?.(event);
    if (!event.defaultPrevented && source?.().popPage()) event.preventDefault();
  }

  /** Clear search and page history after the closing animation. */
  function handleExitComplete(): void {
    local.onExitComplete?.();
    source?.().reset();
  }

  return (
    <Dialog.Root
      lazyMount
      unmountOnExit
      placement="top"
      {...root}
      onEscapeKeyDown={handleEscape}
      onExitComplete={handleExitComplete}
    >
      <Dialog.Context>
        {
          /** Make a close action available to nested Command roots. */
          (dialog) => {
            /** Close through the current primitive dialog machine. */
            function close(): void {
              dialog().setOpen(false);
            }
            return <CommandCloseContext value={close}>{local.children}</CommandCloseContext>;
          }
        }
      </Dialog.Context>
    </Dialog.Root>
  );
}

type CommandContentNativeProps = PrimitiveNativeElementProps<
  'div',
  NativeHtmlAliases & { unstyled?: boolean }
>;
type WithoutNativeTitle<Props> = Props extends unknown ? Omit<Props, 'title'> : never;

/** Accessible title and description supplied by a native Command dialog surface. */
export type CommandDialogContentProps = WithoutNativeTitle<CommandContentNativeProps> & {
  title?: JSX.Element;
  description?: JSX.Element;
};

/** Place Command content with hidden accessible dialog metadata. */
export function CommandDialogContent(props: CommandDialogContentProps): JSX.Element {
  /** Read the primitive title ID used by this dialog's input and result list. */
  const dialog = useDialogContext();
  const [local, content] = splitProps(props, ['title', 'description', 'children']);
  /** Keep the accessible title association reactive to the current dialog. */
  const titleId = createMemo(
    /** Follow the title ID generated by the current primitive dialog. */
    () => dialog().getTitleProps().id || undefined,
  );
  const surface = mergeProps(content, {
    /** Preserve the caller's reactive class after the Command surface hook. */
    get class() {
      return composeRecipeClassNames('command-dialog__content', undefined, content.class);
    },
  });
  return (
    <Dialog.Positioner>
      {/* Omit erases Dialog's polymorphic union; the remaining props still enter its native part. */}
      <CommandDialogSurface {...(surface as DialogContentProps)}>
        <CommandDialogTitleIdContext value={titleId}>
          <Dialog.Title class="leverui-command-dialog__accessible-label">
            {local.title ?? 'Command palette'}
          </Dialog.Title>
          <Dialog.Description class="leverui-command-dialog__accessible-label">
            {local.description ?? 'Search for a command to run'}
          </Dialog.Description>
          {local.children}
        </CommandDialogTitleIdContext>
      </CommandDialogSurface>
    </Dialog.Positioner>
  );
}

/** Reuse the primitive's accessible Dialog trigger within Command compositions. */
export const CommandDialogTrigger = Dialog.Trigger;
/** Reuse the Dialog backdrop within Command compositions. */
export const CommandDialogBackdrop = Dialog.Backdrop;
/** Expose the Dialog machine to Command's descendant actions. */
export const CommandDialogContext = Dialog.Context;
