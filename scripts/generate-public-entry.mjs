import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import ts from 'typescript';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const entryPath = join(projectRoot, 'src/index.ts');
const manifestRoot = join(projectRoot, 'scripts/public-api');
const fragments = [
  'foundation-layout.txt',
  'content.txt',
  'content-names.txt',
  'interactions.txt',
  'platform.txt',
];

/** Accept only relative re-exports in an authored public API fragment. */
function isRelativeExport(statement) {
  return (
    ts.isExportDeclaration(statement) &&
    statement.moduleSpecifier &&
    ts.isStringLiteralLike(statement.moduleSpecifier) &&
    statement.moduleSpecifier.text.startsWith('./')
  );
}

/** Read one small authored fragment and reject invalid entry syntax. */
async function readFragment(name) {
  const source = (await readFile(join(manifestRoot, name), 'utf8')).trimEnd();
  const lines = source.split('\n').length;
  assert.ok(source.length > 0 && lines <= 200, `${name} must have 1–200 lines.`);
  const tree = ts.createSourceFile(name, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  assert.equal(tree.parseDiagnostics.length, 0, `${name} contains invalid TypeScript.`);
  assert.ok(tree.statements.every(isRelativeExport), `${name} must contain only re-exports.`);
  return source;
}

/** Format the curated fragments into the generated package entry. */
async function renderEntry() {
  const blocks = await Promise.all(fragments.map(readFragment));
  const source = [
    '// Generated by scripts/generate-public-entry.mjs. Edit scripts/public-api/*.txt.',
    ...blocks,
    '',
  ].join('\n\n');
  const config = await prettier.resolveConfig(entryPath);
  return prettier.format(source, { ...config, filepath: entryPath });
}

/** Check drift by default; write only when explicitly requested. */
async function main() {
  const expected = await renderEntry();
  const actual = await readFile(entryPath, 'utf8');
  if (process.argv.includes('--write')) {
    if (actual !== expected) await writeFile(entryPath, expected);
    console.log('Generated src/index.ts from curated public API fragments.');
    return;
  }
  assert.equal(actual, expected, 'Public entry drifted; run the generator with --write.');
  console.log('Public entry matches curated API fragments.');
}

await main();
