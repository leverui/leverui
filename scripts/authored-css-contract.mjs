const sharedFamilySources = new Map([['code', ['badge-sizes.css', 'badge-variants.css']]]);

/** Remove CSS comments before checking selectors and attributes. */
function uncommented(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

/** Gather one family's source files without relying on generated CSS output. */
function familySource(sources, family, files) {
  const fragments = [...sources]
    .filter(
      /** Keep only this family's authored CSS fragments. */
      ([name]) =>
        files?.includes(name) ||
        (!files &&
          (name === `${family}.css` ||
            name.startsWith(`${family}-`) ||
            sharedFamilySources.get(family)?.includes(name))),
    )
    .map(
      /** Read the CSS text from one source entry. */
      ([, css]) => css,
    );
  if (fragments.length === 0) throw new Error(`No authored CSS source for ${family}.`);
  return uncommented(fragments.join('\n'));
}

/** Fail the stylesheet build when a migrated public hook or choice disappears. */
export function verifyAuthoredCssContract(sources) {
  for (const { family, required, files } of contracts) {
    const css = familySource(sources, family, files);
    for (const selector of required) {
      if (!css.includes(selector)) {
        throw new Error(`Missing authored ${family} CSS selector: ${selector}`);
      }
    }
  }
}
